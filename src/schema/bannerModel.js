/**
 * Codex — Banner (Minecraft-style heraldry) model + compose.
 *
 * The structured source of truth behind the in-app banner designer. A banner is a **base dye**
 * plus an ordered **painter's stack** of pattern layers, each a `{ pattern, color }` pair:
 *
 *   value = { base: <dyeId>, layers: [ { pattern: <patternId>, color: <dyeId> }, … ≤ MAX_LAYERS ] }
 *
 * `bannerToSvg` is the ONE place that turns that value into markup — mirroring
 * `glyphModel.layersToSvg` — so consumers only ever read the derived string. The rendering is
 * recomputed from the (tiny) value on every read; there is no derived blob to store or keep in sync.
 *
 * Patterns are **pixel-exact**: each is a 20×40 per-pixel ALPHA mask extracted from Minecraft's own
 * banner textures (`bannerPatterns.data.js`, generated by `scripts/extract-banner-patterns.ps1`).
 * Alpha (0–255) carries the shape AND Minecraft's edge anti-aliasing, so nothing here is hand-drawn
 * or synthetically feathered — the pattern id is the game's own (`creeper`, `stripe_top`, …).
 * `bannerToSvg` paints each layer's alpha in its dye, coalescing equal-coverage cells into
 * **run-length merged `<rect>`s** (rows then columns) so output stays crisp vector at any scale.
 *
 * Pure and Node-testable: no DOM, no SDK. The designer component (browser-only) drives it.
 */

import { BANNER_PATTERN_ALPHA } from './bannerPatterns.data.js';

/** The banner face in mask/user space — Minecraft's 20 wide × 40 tall texture. */
export const BANNER_W = 20;
export const BANNER_H = 40;
export const VIEWBOX = `0 0 ${BANNER_W} ${BANNER_H}`;

/** The loom cap: at most 6 pattern layers over the base (mirrors the game). */
export const MAX_LAYERS = 6;

